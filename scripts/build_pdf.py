def style(size=12.5, leading=18, font='T', align=0):
    return ParagraphStyle('text', fontName=font, fontSize=size, leading=leading,
                          alignment=align, textColor=colors.black, splitLongWords=True)


def para(text, x=None, width=None, size=12.5, leading=18, font='T', gap=9, align=0):
    global y
    x = L if x is None else x
    width = CW if width is None else width
    p = Paragraph(text, style(size, leading, font, align))
    _, height = p.wrap(width, 1000)
    if y + height > H - 63:
        raise ValueError(f'Page {page} overflow at {text[:70]}: {y + height:.1f}')
    p.drawOn(C, x, H - y - height)
    y += height + gap
    return height


def text_at(text, x, top, size=11, font='A', align='left'):
    C.setFont(font, size)
    C.setFillColor(colors.black)
    if align == 'center':
        C.drawCentredString(x, H-top, text)
    elif align == 'right':
        C.drawRightString(x, H-top, text)
    else:
        C.drawString(x, H-top, text)


def rect(x, top, width, height, fill=None, stroke='#333333', radius=0):
    C.setStrokeColor(colors.HexColor(stroke))
    C.setLineWidth(.65)
    C.setFillColor(colors.HexColor(fill or '#FFFFFF'))
    if radius:
        C.roundRect(x, H-top-height, width, height, radius, stroke=1, fill=1)
    else:
        C.rect(x, H-top-height, width, height, stroke=1, fill=1)


def line(x1, t1, x2, t2, color='#555555', dashed=False):
    C.setStrokeColor(colors.HexColor(color))
    C.setLineWidth(.7)
    C.setDash(3, 2) if dashed else C.setDash()
    C.line(x1, H-t1, x2, H-t2)
    C.setDash()


def label_box(text, x, top, width, height, size=11, fill='#FFFFFF', bold=False):
    rect(x, top, width, height, fill=fill)
    p = Paragraph(escape(text).replace('\n', '<br/>'), style(size, size*1.25, 'AB' if bold else 'A', 1))
    _, ph = p.wrap(width-14, height)
    if ph > height-8:
        raise ValueError(f'Box overflow: {text}')
    p.drawOn(C, x+7, H-top-(height+ph)/2)


def start(title, anchor, intro=None):
    global page, y
    if page:
        C.showPage()
    page += 1
    C.bookmarkPage(anchor)
    C.addOutlineEntry(title, anchor, level=0, closed=False)
    if page > 1:
        text_at('ВетЗабота | Проектирование информационных систем', L, 35, 8.5, 'A')
        line(L, 44, W-R, 44, '#BBBBBB')
        text_at(str(page), W/2, H-31, 11, 'T', 'center')
    y = 68
    if title:
        para(title, size=15, leading=19, font='TB', gap=15)
    if intro:
        para(intro)


def sub(text):
    para(text, size=12.5, font='TB', gap=7)


def table(headers, rows, widths, size=10.7, leading=14, pad=6):
    global y
    data = [[Paragraph(escape(str(x)).replace('\n', '<br/>'), style(size, leading, 'TB')) for x in headers]]
    for row in rows:
        data.append([Paragraph(escape(str(x)).replace('\n', '<br/>'), style(size, leading)) for x in row])
    t = Table(data, colWidths=widths, repeatRows=1, hAlign='LEFT')
    t.setStyle(TableStyle([
        ('BACKGROUND', (0,0),(-1,0), colors.HexColor('#EEEEEE')),
        ('GRID',(0,0),(-1,-1),.45,colors.HexColor('#BFBFBF')),
        ('VALIGN',(0,0),(-1,-1),'MIDDLE'),
        ('LEFTPADDING',(0,0),(-1,-1),pad),('RIGHTPADDING',(0,0),(-1,-1),pad),
        ('TOPPADDING',(0,0),(-1,-1),pad),('BOTTOMPADDING',(0,0),(-1,-1),pad),
    ]))
    _, th = t.wrap(CW, 1000)
    if y+th > H-63:
        raise ValueError(f'Table overflow on page {page}: {y+th}')
    t.drawOn(C, L, H-y-th)
    y += th+13


def save_record(title, paragraphs):
    records.append((title, paragraphs))


